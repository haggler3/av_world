"""An index of results/: every tracked file, the docs that cite it and the code that writes or reads it.

A file counts as cited by a doc (Markdown, HTML or notebook) or used by code (*.py) when that file mentions its path
from `results/` on (e.g. `results/knee/knee.json`, which also matches `../results/knee/knee.json`). A file mentioned nowhere
is listed as an orphan; a directory-level mention (`results/knee/`) is reported separately, because many tools write
`f"{out}/name.json"`, so an orphan is a candidate for a look, not proof that a file is unused.

python -m avlab.resultsindex            # writes docs/RESULTS_INDEX.md
python -m avlab.resultsindex --check    # exit 1 if a doc links a results/ file that does not exist (git-ignored outputs excepted)
"""
import argparse
import os
import re
import subprocess
import sys
from collections import defaultdict

DOC_EXT = (".md", ".html", ".ipynb")
CODE_EXT = (".py",)
LINK = re.compile(r"results/[A-Za-z0-9_./\-]+\.(?:json|png|gif|csv|npz|md|txt|jsonl|pkl|mp4)")


def tracked(root="."):
    out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout.split("\n")
    return [f for f in out if f]


def build(root="."):
    files = tracked(root)
    res = [f for f in files if f.startswith("results/")]
    texts = {}
    for f in files:
        if f.endswith(DOC_EXT + CODE_EXT) and not f.startswith("results/") and f != "docs/RESULTS_INDEX.md":
            try:
                texts[f] = open(os.path.join(root, f), encoding="utf-8", errors="ignore").read()
            except OSError:
                pass
    cited, used, dir_ref = defaultdict(list), defaultdict(list), defaultdict(list)
    dirs = sorted({os.path.dirname(r) for r in res})
    for f, t in texts.items():
        kind = cited if f.endswith(DOC_EXT) else used
        for r in res:
            if r in t:
                kind[r].append(f)
        for d in dirs:
            if d + "/" in t or f'"{d}"' in t or f"'{d}'" in t:
                dir_ref[d].append(f)
    cand = sorted({(f, m) for f, t in texts.items() if f.endswith(DOC_EXT) for m in LINK.findall(t)
                   if m not in res and not os.path.exists(os.path.join(root, m))})
    # outputs a notebook or tool writes on the user's machine are git-ignored on purpose: not broken
    ign = set(subprocess.run(["git", "check-ignore", "--no-index", "--stdin"], cwd=root, input="\n".join(m for _, m in cand),
                             capture_output=True, text=True).stdout.split("\n")) if cand else set()
    broken = [(f, m) for f, m in cand if m not in ign]
    return {"results": res, "cited": cited, "used": used, "dir_ref": dir_ref, "broken": sorted(broken)}


def render(ix):
    by_dir = defaultdict(list)
    for r in ix["results"]:
        by_dir[os.path.dirname(r)].append(r)
    orph = [r for r in ix["results"] if not ix["cited"].get(r) and not ix["used"].get(r)]
    lines = ["# Results index", "",
             "Generated by `python -m avlab.resultsindex` (do not edit by hand). For every directory of `results/`: how many tracked",
             "files it has, which docs cite its files, and which code mentions it. An *orphan* is a file that no doc and no code",
             "mentions by its own path; most orphans are written by a tool through a directory variable, so check before deleting.", "",
             f"{len(ix['results'])} tracked files in {len(by_dir)} directories; {len(orph)} orphans; "
             f"{len(ix['broken'])} broken results/ links in docs.", "",
             "| directory | files | cited by (docs, file or directory) | mentioned by (code) | orphans |", "|---|---|---|---|---|"]
    for d in sorted(by_dir):
        fs = by_dir[d]
        docs = sorted({x for r in fs for x in ix["cited"].get(r, [])} | {x for x in ix["dir_ref"].get(d, []) if x.endswith(DOC_EXT)})
        code = sorted({x for r in fs for x in ix["used"].get(r, [])} | {x for x in ix["dir_ref"].get(d, []) if x.endswith(CODE_EXT)})
        n_orph = sum(r in orph for r in fs)
        lines.append(f"| `{d}/` | {len(fs)} | {', '.join(f'[{os.path.basename(x)}](../{x})' for x in docs[:6]) + (' ...' if len(docs) > 6 else '') or '-'}"
                     f" | {', '.join(f'`{x}`' for x in code[:4]) + (' ...' if len(code) > 4 else '') or '-'} | {n_orph} |")
    if ix["broken"]:
        lines += ["", "## Broken links", "", "| doc | missing file |", "|---|---|"] + [f"| `{f}` | `{m}` |" for f, m in ix["broken"]]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default="docs/RESULTS_INDEX.md")
    a = ap.parse_args()
    ix = build()
    if a.check:
        for f, m in ix["broken"]:
            print(f"{f}: {m} missing")
        sys.exit(1 if ix["broken"] else 0)
    open(a.out, "w").write(render(ix))
    orph = sum(1 for r in ix["results"] if not ix["cited"].get(r) and not ix["used"].get(r))
    print(f"{len(ix['results'])} files, {orph} orphans, {len(ix['broken'])} broken links -> {a.out}")


if __name__ == "__main__":
    main()
